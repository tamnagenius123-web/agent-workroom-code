/**
 * METER frozen contract — canonical types (v2, contract round 2;
 * section 15 METER-PROVENANCE split piece appended).
 *
 * Type-only module: no runtime code, no behavior change. The prose contract
 * lives in docs/meter-contract.md (v2). Round 2 closes the six items of Dots'
 * pre-acceptance checklist (room msg 0f185036, frozen by PM 9bcc90ee):
 * closed discriminated unions, a v1 inventory + lossless migration, partial
 * success shapes, the J6 observed_at decision, a deterministic replay
 * policy, and a fixed regression-probe registry with expected counts.
 * The zod schema that enforces these shapes in fix6 is pinned as a test
 * contract in tests/meter-contract.test.ts; fix6 adopts it unchanged into
 * the real schema path.
 */

/** Every agent id a v1 snapshot can carry (usage-collect + meter-readers +
 * claude-meter producers). Closed: a new source is a contract change. */
export type UsageAgent =
  | 'codex'
  | 'grok_cli'
  | 'grokbot'
  | 'muse'
  | 'ssu'
  | 'openrouter'
  | 'agy'
  | 'claude';

/** v1 `method` (zod enum in usage.ts). Closed. */
export type UsageMethod = 'measured' | 'ledger' | 'estimated' | 'unavailable';

/** Codex plan labels: the producer allowlist (usage-collect CODEX_PLANS)
 * plus the fixed fallback for anything unrecognized. Closed. */
export type CodexPlan =
  | 'free'
  | 'plus'
  | 'pro'
  | 'team'
  | 'business'
  | 'enterprise'
  | 'edu'
  | 'unrecognized';

/** Per-call status for multi-call sources (SSU credits/usage). Closed. */
export type CallStatus = 'measured' | 'failed' | 'not_attempted';

export type UsedPercentFlag = 'out_of_range';
export type ResetsAtFlag = 'invalid_timestamp';

/** Fixed reason codes. Reasons are codes, never copied untrusted text. */
export type UsageReasonCode =
  | 'no_valid_entries'
  | 'malformed_source'
  | 'fs_error'
  | 'overflow'
  | 'missing'
  | 'gateway_read_failed'
  | 'gateway_timeout'
  | 'parse_failed'
  | 'key_not_set'
  | 'ledger_missing'
  | 'ledger_read_failed'
  | 'ledger_malformed'
  | 'no_local_source'
  | 'conflict';

/**
 * Percent is a discriminated union of exactly three mutually exclusive
 * shapes. `out_of_range` exists only as (null + flag + finite raw); a
 * measured percent never carries flag/raw; an absent/non-numeric percent
 * is plain null with neither. The zod test contract enforces the same
 * exclusivity at runtime for fix6.
 */
export type PercentField =
  | { used_percent: number; used_percent_flag?: undefined; used_percent_raw?: undefined }
  | { used_percent: null; used_percent_flag: UsedPercentFlag; used_percent_raw: number }
  | { used_percent: null; used_percent_flag?: undefined; used_percent_raw?: undefined };

/** Reset timestamp: strict-valid string, plain null (absent), or null + flag
 * (present but invalid). Never a copied raw invalid value. */
export type ResetsAtField =
  | { resets_at: StrictTimestamp; resets_at_flag?: undefined }
  | { resets_at: null; resets_at_flag: ResetsAtFlag }
  | { resets_at: null; resets_at_flag?: undefined };

/**
 * Basis is a closed code plus validated scalar params — never free text.
 * Render builds the human sentence from code + params. v1 free-text basis
 * values migrate through the template table in docs/meter-contract.md §10;
 * an unmapped legacy basis becomes 'legacy_unmapped' and its text is NOT
 * carried into v2 render (it stays in the immutable v1 room message).
 */
export type BasisCode =
  | 'codex_rate_limits'
  | 'codex_stale_reset'
  | 'codex_no_rate_limits'
  | 'ccusage_tokens'
  | 'grokbot_no_source'
  | 'muse_ledger'
  | 'ledger_missing'
  | 'ledger_read_failed'
  | 'ledger_malformed'
  | 'ssu_gateway'
  | 'ssu_no_numeric_fields'
  | 'ssu_partial'
  | 'openrouter_key'
  | 'openrouter_no_usage_field'
  | 'openrouter_key_not_set'
  | 'openrouter_read_failed'
  | 'agy_usage'
  | 'agy_no_numeric_bucket'
  | 'agy_unavailable'
  | 'agy_parse_failed'
  | 'claude_credit_ledger'
  | 'legacy_unmapped';

/** Scalar params a basis template may interpolate. No free text, no paths:
 * the v1 ledger-missing basis embedded a filesystem path; v2 renders the
 * code only (the path stays in local logs, never in a snapshot). */
export interface BasisParams {
  window_minutes?: number | 'unknown';
  plan?: CodexPlan;
  entries?: number;
  group_key?: GroupKey;
  out_of_range?: boolean;
  invalid_timestamp?: boolean;
  expired?: boolean;
}

/** agy group keys are positional, generated by canonicalize: group_1..group_N
 * (1-based, matching meter-readers). A template-literal type, validated by
 * regex in the zod test contract. Untrusted group names never appear. */
export type GroupKey = `group_${number}`;

/** One canonical usage window (codex primary/secondary, agy worst bucket). */
export type CanonicalWindow = PercentField & ResetsAtField & {
  /** Finite positive number or null. */
  window_minutes: number | null;
};

/** Claude per-unit usage (claude-meter units). Unit keys are tracker unit
 * ids matched by the producer's UNIT pattern; values are numeric only.
 * Canonical values are non-negative: in v1 conversion a negative value
 * inside `units` makes the `units` field invalid/dropped (doc §16.8, A1)
 * — unlike a negative amount field, which is overspend (§16.8, A2). */
export interface UnitUsage {
  wakes: number;
  input: number;
  output: number;
  cache_read: number;
  cache_write: number;
  tokens_total: number;
  cost_usd: number;
  api_wakes: number;
}

/** Field-level outcome, so a partial source (e.g. SSU credits OK + usage
 * failed) keeps its valid fields AND names each failed field with a fixed
 * reason — neither half is silently dropped. */
export interface FieldOutcome {
  field:
    | 'credits'
    | 'usage'
    | 'key'
    | 'buckets'
    | 'ledger'
    | 'sessions'
    | 'credit_ledger'
    | 'wake_log';
  status: CallStatus | 'ok' | 'failed';
  reason?: UsageReasonCode;
}

/** An entry skipped inside an otherwise usable source, with a fixed reason. */
export interface SkippedEntry {
  reason: UsageReasonCode | 'invalid_entry' | 'negative_value' | 'non_numeric';
}

/** A timestamp that has passed strict validation (doc section 5/15):
 * exact ISO-8601 UTC shape, every component in range, Date.UTC round-trip
 * reproduces the same components. The brand is compile-time only; the
 * runtime check is `isStrictTimestamp` in tests/meter-contract.test.ts,
 * which fix6 adopts into the real validator. A plain string is NOT a
 * StrictTimestamp and cannot be assigned to a timestamp slot. */
export type StrictTimestamp = string & { readonly __strictTimestamp: unique symbol };

/** Trusted provenance: read server-side from the workroom DB row itself
 * (doc section 15). These four values are the ONLY provenance a selection
 * or render may trust; they never come from the payload being measured. */
export interface TrustedProvenance {
  db_message_id: string;
  db_actor: string;
  db_room: string;
  /** Room time of the DB row (its created_at), strict. */
  db_created_at: StrictTimestamp;
}

/** Untrusted provenance claims carried inside a snapshot payload. Claims
 * are data to be cross-checked against TrustedProvenance, never trusted;
 * a claim field absent means the payload made no claim for it. */
export interface PayloadProvenanceClaims {
  claimed_snapshot_message_id?: string;
  claimed_posted_by?: string;
  claimed_collected_at?: StrictTimestamp;
  claimed_ledger_source_message_id?: string;
}

/** Closed provenance state (doc section 15). `verified`: trusted record
 * present and every present claim matches it. `malformed`: the payload
 * could not be parsed into the claims shape, or a timestamp slot failed
 * strict validation. `conflict`: a present claim differs from the trusted
 * value, or same-id evidence carries a different content hash. `stale`:
 * verified once, but a later failure exists or the max-age bound passed.
 * `unavailable`: no trusted record exists for the attempt. */
export type ProvenanceState = 'verified' | 'malformed' | 'conflict' | 'stale' | 'unavailable';

export interface ProvenanceEnvelope {
  trusted: TrustedProvenance | null;
  payload_claims: PayloadProvenanceClaims;
  state: ProvenanceState;
}

/** One evidence-path entry for same-id decisions (doc section 15): the
 * identity of a stored snapshot is (db_message_id, content_sha256) — the
 * FULL sha256, never a prefix — plus its trusted room time. A
 * message_current pointer is not part of this identity and cannot decide
 * a conflict on its own. */
export interface EvidenceRef {
  db_message_id: string;
  content_sha256: string;
  db_created_at: StrictTimestamp;
}

/** What an unavailable attempt still carries (doc section 15): the trusted
 * provenance of the attempt itself, its strict failure time (or null when
 * the attempt produced no valid time), and a fixed reason code. */
export interface AttemptProvenance {
  trusted: TrustedProvenance;
  failed_at: StrictTimestamp | null;
  reason: UsageReasonCode;
}

/** Stale-redisplay bound (doc section 15): a stale success may be shown
 * to a human, with its latest failure, for at most this long after its
 * valid observation — 86400000 ms (24h). Automated decisions never use a
 * stale record at any age (see staleDecision in the test contract). */
export type STALE_DISPLAY_MAX_AGE_MS = 86400000;

/** Round-2 provenance (doc section 15A): a failure time is discriminated —
 * known ('at'), happened-but-unrecorded ('unknown'), or no failure
 * ('none'). 'unknown' and 'none' are different values; null is not a
 * failure time. */
export type FailureTime =
  | { kind: 'at'; at: StrictTimestamp }
  | { kind: 'unknown' }
  | { kind: 'none' };

/** Round-2 provenance states (doc section 15A.7): the r1 states plus the
 * closed 'unverified' — claims absent, or collector authority not shown.
 * 'unverified' never renders a claimed source id raw (see
 * RenderedSourceId). */
export type ProvenanceStateR2 = ProvenanceState | 'unverified';

/** Round-3 provenance (doc section 15B): selection rejects a same-id
 * group with a missing hash ('missing_content_hash') or divergent
 * hashes ('same_id_divergent_hash') instead of picking a winner. */
export type EvidenceSelectionR3 =
  | { kind: 'selected'; ref: unknown }
  | { kind: 'conflict'; reason: 'same_id_divergent_hash' }
  | { kind: 'unknown_history'; reason: 'missing_content_hash' };

/** Round-3 bound collector authority (doc section 15B.5): the evidence
 * is bound to the trusted record by bound_actor / bound_source /
 * bound_room / evidence_message_id and an expiry. */
export interface BoundCollectorAuthority {
  kind: 'shown';
  bound_actor: string;
  bound_source: string;
  bound_room: string;
  evidence_message_id: string;
  evidence_expires_at: string;
}

/** Collector authority for a source, shown by evidence external to the
 * payload (doc section 15A.7). A DB actor match alone is 'not_shown'. */
export type CollectorAuthority = { kind: 'shown' } | { kind: 'not_shown' };

/** An evidence ref whose hash may be missing (doc section 15A.4): a null
 * content_sha256 is unknown history, decided fail-closed — never a
 * duplicate, distinct or conflict verdict. */
export interface EvidenceRefR2 extends Omit<EvidenceRef, 'content_sha256'> {
  content_sha256: string | null;
  observed_at: StrictTimestamp;
}

/** What render may name for a source (doc section 15A.7): the trusted DB
 * actor of a verified envelope, or the closed unknown variant. */
export type RenderedSourceId = { kind: 'known'; id: string } | { kind: 'unknown_source' };

/** Posting may lag collection by at most this long (doc section 15A.5):
 * 3600000 ms (1h). Collected-after-posting is a conflict. */
export type POSTING_DELAY_MAX_MS = 3600000;

/** Where an observation came from. Preserved through selection and replay:
 * snapshot sources carry the room message id + poster; ledger entries carry
 * their source_message_id. Provenance is never dropped by canonicalize. */
export interface Provenance {
  snapshot_message_id?: string;
  posted_by?: string;
  collected_at?: StrictTimestamp;
  ledger_source_message_id?: string;
}

/** The only shape render may consume for one source (v2). */
export interface CanonicalUsageRecord {
  source: UsageAgent;
  method: UsageMethod;
  percent: PercentField;
  resets: ResetsAtField;
  /** Codex only; closed enum, generated by canonicalize. */
  plan?: CodexPlan;
  basis_code: BasisCode;
  basis_params?: BasisParams;
  tokens_total?: number | null;
  tokens_today?: number | null;
  budget_tokens?: number | null;
  remaining_tokens?: number | null;
  /** SSU credits (credits unit: gateway credits, not USD). */
  credits_remaining?: number | null;
  credits_total?: number | null;
  credits_used?: number | null;
  credits_status?: CallStatus;
  usage_status?: CallStatus;
  /** OpenRouter amounts (USD). Distinct unit from SSU credits — a record
   * never mixes the two families; the zod contract enforces per-source
   * field families. */
  usage_usd?: number | null;
  limit_usd?: number | null;
  remaining_usd?: number | null;
  /** Claude prepaid credit (USD) + per-unit usage. */
  spent_usd?: number | null;
  remaining_credit_usd?: number | null;
  credit_expired?: boolean;
  credit_expires_at?: StrictTimestamp | null;
  /** agy per-group minimum remaining fraction, positional keys only. */
  agy_groups_min_remaining_fraction?: Partial<Record<GroupKey, number>>;
  units?: Record<string, UnitUsage>;
  windows?: CanonicalWindow[];
  /** Strict timestamp or null (J6: invalid -> null, source preserved). */
  observed_at: StrictTimestamp | null;
  provenance: Provenance;
}

/**
 * Per-source isolation unit. Three mutually exclusive kinds:
 * - ok: a record with at least one valid measurement, no failed field.
 * - partial: a record with at least one valid measurement AND at least one
 *   failed field (named in `fields`). SSU credits-ok/usage-failed is this.
 * - unavailable: no valid measurement. Carries the fixed reason and the
 *   failure time; never a record, never a numeric zero.
 */
export type SourceResult =
  | { kind: 'ok'; record: CanonicalUsageRecord; fields: FieldOutcome[]; skipped: SkippedEntry[] }
  | { kind: 'partial'; record: CanonicalUsageRecord; fields: FieldOutcome[]; skipped: SkippedEntry[] }
  | {
      kind: 'unavailable';
      source: UsageAgent;
      reason: UsageReasonCode;
      /** Strict timestamp of the failed attempt, or null if none exists. */
      failed_at: StrictTimestamp | null;
      fields: FieldOutcome[];
    };

/** What latest-selection keeps per agent (replay policy, doc §13): the
 * latest valid record and the latest attempt are separate slots, so a
 * failure after a success never erases the last valid measurement. */
export interface AgentLatest {
  valid: CanonicalUsageRecord | null;
  latest_attempt: SourceResult | null;
}

/**
 * METER-SCHEMA-V1 (split piece 2 of 3, doc §16): the v1 acceptance and
 * conversion shapes. Conversion is a consumer-side interpretation of the
 * immutable v1 snapshot; every present field is tracked exactly once.
 * A field's value state is exactly one of normal (finite, in range, or a
 * plain null under J6), out_of_range (a FINITE raw outside its range —
 * never NaN or +/-Infinity), or invalid. The action records what
 * conversion did with it: carried unchanged, mapped to the canonical
 * shape, or dropped with a UsageReasonCode — reasons are codes from the
 * same closed list the zod schema enforces, never copied text.
 */
export type V1FieldState = 'normal' | 'out_of_range' | 'invalid';
export type V1ConversionAction = 'carried' | 'mapped' | 'dropped';
export interface FieldConversion {
  field: string;
  state: V1FieldState;
  action: V1ConversionAction;
  reason?: UsageReasonCode;
}
/** Per-source conversion outcome. `unknown_source` is the closed variant
 * for an agent outside the UsageAgent union: the record migrates to an
 * unavailable/malformed_source reading and the raw agent string is never
 * carried or rendered. `invalid_source` is a source whose own fields
 * contradict the contract (e.g. credits and USD families mixed). */
export type SourceConversion =
  | {
      outcome: 'converted';
      source: UsageAgent;
      fields: FieldConversion[];
      /** R2 (doc §16.7): conversion returns the canonical VALUES, not only
       * the tracking ledger — carried/mapped fields land here with their
       * canonical values (timestamps as UTC Z, an out-of-range percent as
       * null+flag+raw, invalid timestamps as null, stored nulls as null,
       * genuine zeros as zero), and `record.provenance.collected_at`
       * carries the envelope time. Dropped fields never appear.
       * R3 (doc §16.8, F1): this variant is the ONE converted shape and
       * this type is its source of truth (fix6 consumes it). There is NO
       * top-level provenance on the variant: provenance lives inside the
       * record (`record.provenance`), there is no `provenance.source`,
       * and the source is the variant's `source` / `record.source`. The
       * test-contract reference returns exactly this shape, and its
       * regression test parses `record` with the canonicalRecord schema
       * (which also covers `units` and `windows`, as this type does). */
      record: CanonicalUsageRecord;
      /** A present string null_reason, mapped to its closed code (§9). */
      null_reason_code?: UsageReasonCode;
    }
  | { outcome: 'unknown_source'; fields: FieldConversion[] }
  | { outcome: 'invalid_source'; fields: FieldConversion[] };
/** Snapshot-level conversion outcome. `unsupported_version` is closed:
 * the unsupported kind string is never echoed into the result. */
export type SnapshotConversion =
  | { outcome: 'converted'; sources: SourceConversion[] }
  | { outcome: 'unsupported_version' }
  | { outcome: 'invalid_snapshot'; reason: UsageReasonCode };
